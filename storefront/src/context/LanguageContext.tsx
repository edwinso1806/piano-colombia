const LanguageContext = createContext<LanguageContextType>({
  language: "es",
  setLanguage: () => {},
  t: (key, fallback) => fallback || key,
})

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("es")

  useEffect(() => {
    try {
      const stored = localStorage.getItem("piano_colombia_lang") as Language
      if (stored === "es" || stored === "en") {
        setLanguageState(stored)
      } else {
        const cookieMatch = document.cookie.match(/(?:^|; )piano_colombia_lang=(es|en)/)
        if (cookieMatch && (cookieMatch[1] === "es" || cookieMatch[1] === "en")) {
          setLanguageState(cookieMatch[1] as Language)
        }
      }
    } catch {
      // Fallback a español si localStorage no está accesible
    }
  }, [])

  const setLanguage = (lang: Language) => {
    setLanguageState(lang)
    if (typeof window !== "undefined") {
      try {
        localStorage.setItem("piano_colombia_lang", lang)
        document.cookie = `piano_colombia_lang=${lang}; path=/; max-age=31536000; SameSite=Lax`
      } catch {
        // Ignorar
      }
    }
  }

  const t = (key: string, fallback?: string): string => {
    const langDict = translations[language] || translations.es
    return langDict[key] || fallback || key
  }

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  return useContext(LanguageContext)
}
