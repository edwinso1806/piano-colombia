const LanguageContext = createContext<LanguageContextType>({
  language: "es",
  setLanguage: () => {},
  t: (key, fallback) => fallback || key,
})

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window !== "undefined") {
      try {
        const stored = localStorage.getItem("piano_colombia_lang") as Language
        if (stored === "es" || stored === "en") {
          return stored
        }
      } catch {
        // Fallback a español si localStorage no está accesible
      }
    }
    return "es"
  })

  const setLanguage = (lang: Language) => {
    setLanguageState(lang)
    if (typeof window !== "undefined") {
      try {
        localStorage.setItem("piano_colombia_lang", lang)
      } catch {
        // Ignorar
      }
    }
  }

  const t = (key: string, fallback?: string): string => {
    const langDict = translations[language] || translations.es
    return langDict[key] || fallback || key
  }

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  return useContext(LanguageContext)
}
